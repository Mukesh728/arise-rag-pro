-- Arise durable storage migration for Supabase Free.
-- Run in Supabase SQL Editor before enabling VECTOR_STORE_TYPE=pgvector.
-- This migration is additive and does not delete or rewrite existing rows.

create extension if not exists vector;

create table if not exists public.arise_users (
  id text primary key,
  email text not null unique,
  password_hash text not null,
  role text not null default 'user',
  created_at double precision not null default extract(epoch from now()),
  token_version integer not null default 0
);

create table if not exists public.arise_documents (
  id text primary key,
  user_id text not null,
  filename text not null,
  subject text not null,
  unit text,
  total_pages integer not null default 0,
  total_chunks integer not null default 0,
  storage_path text not null,
  uploaded_at double precision not null default extract(epoch from now())
);
create index if not exists arise_documents_user_idx on public.arise_documents(user_id, uploaded_at desc);

create table if not exists public.arise_chunks (
  chunk_id text primary key,
  doc_id text not null,
  owner_user_id text not null,
  filename text not null,
  subject text not null,
  unit integer,
  page_number integer not null,
  char_start integer not null default 0,
  char_end integer not null default 0,
  token_count integer not null default 0,
  content text not null,
  embedding vector(384) not null,
  created_at timestamptz not null default now()
);
create index if not exists arise_chunks_owner_idx on public.arise_chunks(owner_user_id);
create index if not exists arise_chunks_doc_idx on public.arise_chunks(doc_id);
create index if not exists arise_chunks_subject_idx on public.arise_chunks(owner_user_id, subject);
create index if not exists arise_chunks_embedding_hnsw on public.arise_chunks using hnsw (embedding vector_cosine_ops);

create table if not exists public.arise_chat_history (
  id bigint generated by default as identity primary key,
  user_id text not null,
  question text not null,
  answer text not null default '',
  mode text not null default 'hybrid',
  subject text,
  citations jsonb not null default '[]'::jsonb,
  is_fallback boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists arise_chat_history_user_idx on public.arise_chat_history(user_id, created_at desc);

-- Private bucket: only the backend service role should access it.
insert into storage.buckets (id, name, public)
values ('arise-pdfs', 'arise-pdfs', false)
on conflict (id) do nothing;

-- Backend uses the server-side database/service role. RLS prevents accidental
-- anon/authenticated access if the tables are ever reached through PostgREST.
alter table public.arise_users enable row level security;
alter table public.arise_documents enable row level security;
alter table public.arise_chunks enable row level security;
alter table public.arise_chat_history enable row level security;

-- No public policies are created intentionally. The Render backend connects
-- with the Supabase service role / database owner and is the only application
-- access path. Never put either credential in frontend code.
